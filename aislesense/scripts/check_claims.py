MARK = re.compile(r"\{\{([a-z0-9_]+)\}\}")


def _get(d, path):
    for p in path.split("."):
        d = d[int(p)] if isinstance(d, list) else d[p]
    return d


_cache: dict = {}


def value(key: str, results: Path = RESULTS) -> str:
    fname, path, fmt, _ = K[key]
    fp = results / fname
    if fp not in _cache:
        _cache[fp] = json.loads(fp.read_text(encoding="utf-8"))
    d = _cache[fp]
    if callable(path):
        v = path(d)
    elif isinstance(path, list):
        v = [_get(d, p) for p in path]
    else:
        v = _get(d, path)
    return fmt(v)


def render(text: str, results: Path = RESULTS, errors: list | None = None, where: str = "") -> str:
    def sub(m):
        k = m.group(1)
        if k not in K:
            if errors is not None:
                errors.append(f"{where}: unknown claim key {{{{{k}}}}}")
            return m.group(0)
        try:
            return value(k, results)
        except (KeyError, IndexError, TypeError, ValueError, FileNotFoundError) as e:
            if errors is not None:
                errors.append(f"{where}: {{{{{k}}}}} does not resolve in results/{K[k][0]} ({e!r})")
            return m.group(0)
    return MARK.sub(sub, text)


def _strip_nonprose(text: str) -> list[tuple[int, str]]:
    """Lines with code blocks, inline code, links, comments, tags and markers removed."""
    out, fence = [], False
    for n, line in enumerate(text.splitlines(), 1):
        if line.strip().startswith("```"):
            fence = not fence
            continue
        if fence:
            continue
        s = re.sub(r"`[^`]*`", " ", line)
        s = re.sub(r"<!--.*?-->", " ", s)
        s = re.sub(r"\]\([^)]*\)", "]", s)
        s = re.sub(r"https?://\S+", " ", s)
        s = re.sub(r"\[(?:[EDXAP]\d+(?:\]\[[EDXAP]\d+)*)\]", " ", s)
        s = MARK.sub(" ", s)
        s = re.sub(r"^\s*(?:#+\s*)?\d+(?:\.\d+)*[.)]?\s", " ", s)  # heading / ordered-list numbering
        s = re.sub(r"^\s*\|\s*\d+\s*\|", "| |", s)          # row-number column in tables
        out.append((n, s))
    return out


def free_numbers(text: str, where: str = "") -> list[str]:
    errs = []
    for n, s in _strip_nonprose(text):
        for pat, _ in FREE:
            s = re.sub(pat, " ", s)
        for m in re.finditer(r"\d+(?:[.,]\d+)*%?", s):
            errs.append(f"{where}:{n}: free number '{m.group(0)}' not from results/ (use a {{{{key}}}} marker or add a FREE rule with a reason)")
    return errs


def _blocks(text: str):
    """Paragraphs (blank-line separated); table rows are their own block."""
    block, start = [], 1
    for n, line in enumerate(text.splitlines() + [""], 1):
        if line.strip().startswith("|"):
            if block:
                yield start, "\n".join(block)
                block = []
            yield n, line
            start = n + 1
        elif not line.strip():
            if block:
                yield start, "\n".join(block)
            block, start = [], n + 1
        else:
            if not block:
                start = n
            block.append(line)


def prior_adjacency(text: str, where: str = "") -> list[str]:
    errs = []
    for n, b in _blocks(text):
        keys = set(MARK.findall(b))
        for k in keys:
            if k in K and K[k][3] and K[k][3] not in keys:
                errs.append(f"{where}:{n}: headline {{{{{k}}}}} without its prior/baseline {{{{{K[k][3]}}}}} in the same row or paragraph")
    return errs


def banned(text: str, where: str = "", team_scored: bool = False) -> list[str]:
    text = re.sub(r"<!-- claims:quote -->.*?<!-- /claims:quote -->", "", text, flags=re.S)
    rules = BANNED + ([] if team_scored else BANNED_UNTIL_TEAM)
    errs = []
    for n, line in enumerate(text.splitlines(), 1):
        for pat, why in rules:
            m = re.search(pat, line, flags=re.I)
            if m:
                errs.append(f"{where}:{n}: banned claim '{m.group(0)}' ({why})")
    return errs


def first_slide(sources: dict, results: Path = RESULTS) -> list[str]:
    name, key, fname, expect = FIRST_SLIDE
    src = sources.get(name, "")
    lines = [l for l in src.splitlines() if "first-slide number" in l.lower()]
    if not lines or "{{" + key + "}}" not in lines[0]:
        return [f"{name}: first-slide number line must carry {{{{{key}}}}}"]
    if K[key][0] != fname:
        return [f"{name}: first-slide key resolves to {K[key][0]}, expected {fname}"]
    got = value(key, results)
    return [] if got == expect else [f"{name}: first-slide number reads '{got}', expected '{expect}'"]


def claims_table(sources: dict, results: Path = RESULTS) -> str:
    used = sorted({k for s in sources.values() for k in MARK.findall(s) if k in K})
    rows = ["# Claims table", "",
            GENERATED.format(name="*").strip(), "",
            "Every number in README.md, docs/report.md, docs/demo_script.md and docs/filming_guide.md comes from one of these keys. "
            "`python scripts/check_claims.py` rebuilds each value from `results/` and fails on any mismatch.", "",
            "| Key | Value | Results field | Prior / baseline beside it |", "|---|---|---|---|"]
    for k in used:
        fname, path, _, prior = K[k]
        p = "derived" if callable(path) else (" + ".join(path) if isinstance(path, list) else path)
        pv = f"{prior} = {value(prior, results)}" if prior else ""
        rows.append(f"| `{k}` | {value(k, results)} | `results/{fname}` `{p}` | {pv} |")
    return "\n".join(rows) + "\n"


def check(write: bool = False, src_dir: Path = SRC, outputs: dict = OUTPUTS, results: Path = RESULTS,
          claims_md: Path = CLAIMS_MD) -> list[str]:
    _cache.clear()
    errs: list[str] = []
    sources = {}
    for name, out in outputs.items():
        sp = src_dir / name
        if not sp.exists():
            errs.append(f"missing source docs/src/{name}")
            continue
        sources[name] = sp.read_text(encoding="utf-8")
    team_scored = (results / "staged_team.json").exists()
    for name, text in sources.items():
        rendered = GENERATED.format(name=name) + render(text, results, errs, name)
        errs += free_numbers(text, name)
        errs += prior_adjacency(text, name)
        errs += banned(rendered, outputs[name].name, team_scored)
        out = outputs[name]
        if write:
            out.write_text(rendered, encoding="utf-8", newline="\n")
        elif not out.exists() or out.read_text(encoding="utf-8") != rendered:
            errs.append(f"{out.relative_to(ROOT) if out.is_relative_to(ROOT) else out}: differs from a fresh render of results/ (stale or hand-edited number; run --write)")
    errs += first_slide(sources, results)
    if not errs or write:
        table = claims_table(sources, results)
        if write:
            claims_md.write_text(table, encoding="utf-8", newline="\n")
        elif not claims_md.exists() or claims_md.read_text(encoding="utf-8") != table:
            errs.append("docs/claims.md differs from a fresh render (run --write)")
    return errs


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true", help="re-render docs and claims.md from results/")
    a = ap.parse_args(argv)
    if not SRC.exists():
        # docs/ is kept out of git; only the rendered README.md ships. Nothing to check in a clone.
        print("check_claims: docs/src/ not in this checkout; skipped (README.md is rendered by the maintainer)")
        return 0
    errs = check(write=a.write)
    for e in errs:
        print("FAIL", e)
    n_keys = len({k for p in OUTPUTS for k in MARK.findall((SRC / p).read_text(encoding="utf-8")) if (SRC / p).exists()})
    print(f"check_claims: {len(errs)} problems; {n_keys} keys rendered from results/; first slide = {value(FIRST_SLIDE[1])} ({FIRST_SLIDE[2]})")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
