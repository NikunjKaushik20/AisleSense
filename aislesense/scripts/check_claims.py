"""Claims check for AisleSense docs (M7).

Every number a human reads in README.md, docs/report.md, docs/demo_script.md and docs/filming_guide.md is
rendered from results/*.json. The editable sources live in docs/src/; a number enters them only as a
{{key}} marker, and every key is defined below as (results file, field path, format, prior key).

    python scripts/check_claims.py           # check: exit 0 only if everything holds
    python scripts/check_claims.py --write   # re-render the docs and docs/claims.md from results/

Checks (all must pass):
  1. every {{key}} in a source resolves to a field in results/*.json;
  2. the rendered docs on disk equal a fresh render (no hand-edited or stale number);
  3. no free number in a source outside code, tags and the FREE allowlist (protocol constants, not results);
  4. every headline key sits next to its prior or baseline key (same table row, else same paragraph);
  5. no banned claim ("first ...", "detects blocks" before team staged scoring exists, dense crowds,
     ATC as detector proof, state of the art) outside <!-- claims:quote --> regions;
  6. the first-slide number in docs/demo_script.md reads "0 of 656" and resolves to results/atc_deadzone.json.
"""
